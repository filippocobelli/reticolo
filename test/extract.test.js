// node test/extract.test.js
const assert = require('node:assert');
const zlib = require('node:zlib');
const fflate = require('fflate');
const X = require('../electron/extract');
const { encodePng } = X._internal;

const png = (w, h, c = [200, 50, 50, 255]) => { const b = Buffer.alloc(w * h * 4); for (let i = 0; i < w * h; i++) b.set(c, i * 4); return encodePng(w, h, b); };
const isPng = (b) => b && b[0] === 0x89 && b.toString('latin1', 1, 4) === 'PNG';
const dims = (b) => [b.readUInt32BE(16), b.readUInt32BE(20)];
const wrap = (b64) => b64.match(/.{1,78}/g).map(l => '; ' + l).join('\n');

(async () => {
  // ---- G-code testuale con due miniature ----
  const small = png(32, 32), large = png(220, 124);
  const gcode = [
    '; generated by PrusaSlicer 2.7.1+linux-x64 on 2026-01-01 at 10:00:00 UTC', ';',
    `; thumbnail begin 32x32 ${small.toString('base64').length}`, wrap(small.toString('base64')), '; thumbnail end', ';',
    `; thumbnail begin 220x124 ${large.toString('base64').length}`, wrap(large.toString('base64')), '; thumbnail end', ';',
    'G28', 'G1 X10 Y10 E1', 'G1 X20 Y10 E2',
    '; filament used [mm] = 1234.5, 100.5', '; filament used [g] = 3.70, 0.30',
    '; estimated printing time (normal mode) = 1h 2m 30s', '; layer_height = 0.2', '; filament_type = PLA;PETG', '; printer_model = MK4', '; nozzle_diameter = 0.4',
  ].join('\n');
  const gi = { name: 'parte.gcode', ext: 'gcode', kind: 'gcode' };
  const t = await X.extractThumbnail(gi, Buffer.from(gcode));
  assert.ok(isPng(t)); assert.deepStrictEqual(dims(t), [220, 124]);
  const gm = await X.extractMeta(gi, Buffer.from(gcode));
  assert.strictEqual(gm.printMinutes, 62.5); assert.strictEqual(gm.filamentG, 4); assert.strictEqual(gm.filamentM, 1.335);
  assert.strictEqual(gm.layerHeight, 0.2); assert.match(gm.slicer, /PrusaSlicer 2\.7\.1/); assert.strictEqual(gm.thumbnails, 2);
  console.log('ok gcode', gm);
  // Cura / Bambu
  const cura = ';FLAVOR:Marlin\n;TIME:5400\n;Filament used: 2.5m\n;Layer height: 0.12\n;MATERIAL:PLA\n;Generated with Cura_SteamEngine 5.6.0\nG1 X1\n';
  const cm = await X.extractMeta(gi, Buffer.from(cura));
  assert.strictEqual(cm.printMinutes, 90); assert.strictEqual(cm.filamentM, 2.5); assert.match(cm.slicer, /Cura/);
  const bambu = '; HEADER_BLOCK_START\n; BambuStudio 01.09.00.70\n; model printing time: 1h 2m 3s; total estimated time: 1h 10m 0s\n; total layer number: 150\n; total filament weight [g] : 12.34\n; HEADER_BLOCK_END\n';
  const bm = await X.extractMeta(gi, Buffer.from(bambu));
  assert.strictEqual(bm.printMinutes, 70); assert.strictEqual(bm.filamentG, 12.34); assert.strictEqual(bm.layers, 150); assert.match(bm.slicer, /BambuStudio/);
  console.log('ok cura/bambu');

  // ---- bgcode ----
  const bg = [];
  const head = Buffer.alloc(10); head.write('GCDE'); head.writeUInt32LE(1, 4); head.writeUInt16LE(1, 8); bg.push(head);
  const block = (type, params, data, comp = 0) => {
    const raw = comp === 1 ? zlib.deflateSync(data) : data;
    const h = Buffer.alloc(comp ? 12 : 8); h.writeUInt16LE(type, 0); h.writeUInt16LE(comp, 2); h.writeUInt32LE(data.length, 4); if (comp) h.writeUInt32LE(raw.length, 8);
    return Buffer.concat([h, params, raw, Buffer.alloc(4)]);
  };
  bg.push(block(0, Buffer.from([0, 0]), Buffer.from('Producer=PrusaSlicer 2.8.0\n')));
  const tp = Buffer.alloc(6); tp.writeUInt16LE(0, 0); tp.writeUInt16LE(220, 2); tp.writeUInt16LE(124, 4);
  bg.push(block(5, tp, large));
  bg.push(block(4, Buffer.from([0, 0]), Buffer.from('filament used [g]=5.5\nestimated printing time (normal mode)=2h 0m 0s\n'), 1));
  const bgb = Buffer.concat(bg);
  const bi = { name: 'x.bgcode', ext: 'bgcode' };
  assert.deepStrictEqual(dims(await X.extractThumbnail(bi, bgb)), [220, 124]);
  const bgm = await X.extractMeta(bi, bgb);
  assert.strictEqual(bgm.printMinutes, 120); assert.strictEqual(bgm.filamentG, 5.5); assert.match(bgm.slicer, /PrusaSlicer/);
  console.log('ok bgcode', bgm);

  // ---- LightBurn ----
  const lb = `<?xml version="1.0"?><LightBurnProject AppVersion="1.4.03" FormatVersion="1"><Thumbnail Source="${large.toString('base64')}"/><CutSetting type="Cut"/><Shape Type="Rect"/><Shape Type="Ellipse"/></LightBurnProject>`;
  const li = { name: 'a.lbrn2', ext: 'lbrn2' };
  assert.deepStrictEqual(dims(await X.extractThumbnail(li, Buffer.from(lb))), [220, 124]);
  const lm = await X.extractMeta(li, Buffer.from(lb)); assert.strictEqual(lm.shapes, 2); assert.match(lm.application, /LightBurn/);
  console.log('ok lightburn', lm);

  // ---- xTool XCS (JSON con data URL) ----
  const xcs = JSON.stringify({ version: '2.0', canvas: [{ id: 1 }], cover: `data:image/png;base64,${large.toString('base64')}` });
  assert.deepStrictEqual(dims(await X.extractThumbnail({ name: 'a.xcs', ext: 'xcs' }, Buffer.from(xcs))), [220, 124]);
  console.log('ok xcs');

  // ---- 3MF Bambu con miniature e slice_info ----
  const model = '<?xml version="1.0"?><model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><metadata name="Application">BambuStudio-01.09.00.70</metadata><resources><object id="1" name="Cubo" type="model"><mesh><vertices><vertex x="0" y="0" z="0"/></vertices><triangles><triangle v1="0" v2="0" v3="0"/><triangle v1="0" v2="0" v3="0"/></triangles></mesh></object></resources><build><item objectid="1"/></build></model>';
  const sliceInfo = '<?xml version="1.0"?><config><header><header_item key="X-BBL-Client-Version" value="01.09"/></header><plate><metadata key="index" value="1"/><metadata key="prediction" value="3600"/><metadata key="weight" value="10.5"/><filament id="1" type="PLA" color="#FF0000" used_m="3.2" used_g="10.5"/></plate><plate><metadata key="index" value="2"/><metadata key="prediction" value="1800"/><metadata key="weight" value="4.5"/><filament id="2" type="PETG" color="#00FF00" used_m="1.4" used_g="4.5"/></plate></config>';
  const mset = '<config><plate><metadata key="plater_id" value="1"/></plate><plate><metadata key="plater_id" value="2"/></plate></config>';
  const z = fflate.zipSync({ '3D/3dmodel.model': Buffer.from(model), 'Metadata/plate_1.png': large, 'Metadata/plate_1_small.png': small, 'Metadata/plate_2.png': png(64, 64), 'Metadata/slice_info.config': Buffer.from(sliceInfo), 'Metadata/model_settings.config': Buffer.from(mset) });
  const ti = { name: 'p.3mf', ext: '3mf' };
  const t3 = await X.extractThumbnail(ti, Buffer.from(z));
  assert.deepStrictEqual(dims(t3), [220, 124]);
  const m3 = await X.extractMeta(ti, Buffer.from(z));
  assert.strictEqual(m3.printMinutes, 90); assert.strictEqual(m3.filamentG, 15); assert.strictEqual(m3.plates.length, 2); assert.strictEqual(m3.plateCount, 2);
  assert.strictEqual(m3.triangles, 2); assert.deepStrictEqual(m3.objects, ['Cubo']); assert.match(m3.material, /PLA, PETG/);
  console.log('ok 3mf', JSON.stringify(m3));
  // 3MF generico con Metadata/thumbnail.png
  const z2 = fflate.zipSync({ '3D/3dmodel.model': Buffer.from(model), 'Metadata/thumbnail.png': png(100, 100) });
  assert.deepStrictEqual(dims(await X.extractThumbnail(ti, Buffer.from(z2))), [100, 100]);

  // ---- DWG con sezione di anteprima PNG + BMP ----
  const sentinel = Buffer.from([0x1f, 0x25, 0x6d, 0x07, 0xd4, 0x36, 0x28, 0x28, 0x9d, 0x57, 0xca, 0x3f, 0x9d, 0x44, 0x10, 0x2b]);
  const mkDwg = (code, payload) => {
    const hdr = Buffer.alloc(0x80); hdr.write('AC1032', 0, 'latin1'); hdr.writeUInt32LE(0x80, 0x0d);
    const sec = Buffer.alloc(16 + 4 + 1 + 9); sentinel.copy(sec, 0); sec.writeUInt32LE(payload.length, 16); sec[20] = 1;
    sec[21] = code; sec.writeUInt32LE(0x80 + sec.length, 22); sec.writeUInt32LE(payload.length, 26);
    return Buffer.concat([hdr, sec, payload, Buffer.alloc(100)]);
  };
  const di = { name: 'pianta.dwg', ext: 'dwg' };
  assert.deepStrictEqual(dims(await X.extractThumbnail(di, mkDwg(6, large))), [220, 124]);
  // BMP 24 bit 40x36
  const W = 40, H = 36, stride = Math.ceil(W * 3 / 4) * 4;
  const dib = Buffer.alloc(40 + stride * H); dib.writeUInt32LE(40, 0); dib.writeInt32LE(W, 4); dib.writeInt32LE(H, 8); dib.writeUInt16LE(1, 12); dib.writeUInt16LE(24, 14);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) { const p = 40 + y * stride + x * 3; dib[p] = 255; dib[p + 1] = 0; dib[p + 2] = 0; }
  const bt = await X.extractThumbnail(di, mkDwg(2, dib));
  assert.ok(isPng(bt)); assert.deepStrictEqual(dims(bt), [W, H]);
  assert.strictEqual((await X.extractMeta(di, mkDwg(6, large))).dwgVersion, 'AC1032');
  console.log('ok dwg (png + bmp)');

  // ---- fallback generico (PNG incorporato in binario sconosciuto) ----
  const junk = Buffer.concat([Buffer.alloc(5000, 1), png(16, 16), Buffer.alloc(300, 2), png(48, 48), Buffer.alloc(1000, 3)]);
  assert.deepStrictEqual(dims(await X.extractThumbnail({ name: 'a.3dm', ext: '3dm' }, junk)), [48, 48]);
  // Fusion F3D (zip con anteprima)
  const f3d = fflate.zipSync({ 'FusionAssetName[Active]/Previews/small.png': png(64, 64), 'data.bin': Buffer.alloc(10) });
  assert.deepStrictEqual(dims(await X.extractThumbnail({ name: 'a.f3d', ext: 'f3d' }, Buffer.from(f3d))), [64, 64]);
  const f3z = fflate.zipSync({ 'a.f3d': f3d });
  assert.deepStrictEqual(dims(await X.extractThumbnail({ name: 'a.f3z', ext: 'f3z' }, Buffer.from(f3z))), [64, 64]);
  console.log('ok generico / fusion');

  // ---- STL / OBJ / STEP ----
  const stl = Buffer.alloc(84 + 3 * 50); stl.writeUInt32LE(3, 80);
  assert.deepStrictEqual(await X.extractMeta({ name: 'a.stl', ext: 'stl' }, stl), { stlFormat: 'binary', triangles: 3 });
  const astl = 'solid a\nfacet normal 0 0 1\nouter loop\nendloop\nendfacet\nfacet normal 0 0 1\nendfacet\nendsolid a\n';
  assert.strictEqual((await X.extractMeta({ name: 'a.stl', ext: 'stl' }, Buffer.from(astl))).triangles, 2);
  assert.deepStrictEqual(await X.extractMeta({ name: 'a.obj', ext: 'obj' }, Buffer.from('v 0 0 0\nv 1 0 0\nv 0 1 0\nvn 0 0 1\nf 1 2 3\n')), { vertices: 3, faces: 1 });
  const step = "ISO-10303-21;\nHEADER;\nFILE_DESCRIPTION((''),'2;1');\nFILE_NAME('staffa.step','2026-01-01T00:00:00',('Mario Rossi'),('Officina'),'ST-DEVELOPER','SolidWorks 2024','');\nFILE_SCHEMA(('AUTOMOTIVE_DESIGN'));\nENDSEC;\nDATA;\n#1=PRODUCT('Staffa','Staffa',' ',(#2));\n#3=PRODUCT('Vite M3','Vite M3',' ',(#2));\nENDSEC;\nEND-ISO-10303-21;\n";
  const sm = await X.extractMeta({ name: 'a.step', ext: 'step' }, Buffer.from(step));
  assert.deepStrictEqual(sm.products, ['Staffa', 'Vite M3']); assert.strictEqual(sm.author, 'Mario Rossi'); assert.strictEqual(sm.originatingSystem, 'SolidWorks 2024');
  assert.strictEqual(await X.extractThumbnail({ name: 'a.step', ext: 'step' }, Buffer.from(step)), null);
  console.log('ok stl/obj/step', sm);

  // ---- robustezza ----
  for (const ext of ['3mf', 'gcode', 'bgcode', 'lbrn', 'xcs', 'dwg', 'f3d', 'lys', 'stl', 'step', 'obj']) {
    assert.strictEqual(await X.extractThumbnail({ name: 'x.' + ext, ext }, Buffer.from('spazzatura')), null);
    assert.ok(typeof (await X.extractMeta({ name: 'x.' + ext, ext }, Buffer.from([0x50, 0x4b, 3, 4, 9]))) === 'object');
    assert.strictEqual(await X.extractThumbnail({ name: 'x.' + ext, ext }, null), null);
  }
  console.log('EXTRACT OK');
})().catch((e) => { console.error(e); process.exit(1); });
