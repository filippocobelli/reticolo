// Genera una libreria di prova realistica in una cartella.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { zipSync, strToU8 } = require('fflate');
const { modelFromObjects, write3mf, writeStl } = require('../electron/threemf');
const { _internal: { encodePng } } = require('../electron/extract');

function box(w, d, h, ox = 0, oy = 0, oz = 0) {
  const v = [[0,0,0],[w,0,0],[w,d,0],[0,d,0],[0,0,h],[w,0,h],[w,d,h],[0,d,h]].map(([x,y,z]) => [x+ox,y+oy,z+oz]);
  const f = [[0,2,1],[0,3,2],[4,5,6],[4,6,7],[0,1,5],[0,5,4],[1,2,6],[1,6,5],[2,3,7],[2,7,6],[3,0,4],[3,4,7]];
  return new Float32Array(f.flatMap(t => t.flatMap(i => v[i])));
}
function cylinder(r, h, n = 48, ox = 0, oy = 0) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = i / n * Math.PI * 2, b = (i + 1) / n * Math.PI * 2;
    const p = (ang, z) => [ox + Math.cos(ang) * r, oy + Math.sin(ang) * r, z];
    out.push(...[ox, oy, 0], ...p(b, 0), ...p(a, 0));
    out.push(...[ox, oy, h], ...p(a, h), ...p(b, h));
    out.push(...p(a, 0), ...p(b, 0), ...p(b, h), ...p(a, 0), ...p(b, h), ...p(a, h));
  }
  return new Float32Array(out);
}
function png(w, h, color) {
  const rgba = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = (y * w + x) * 4, d = Math.hypot(x - w / 2, y - h / 2) / (w / 2);
    rgba[i] = color[0] * (1 - d * .5); rgba[i + 1] = color[1] * (1 - d * .5); rgba[i + 2] = color[2] * (1 - d * .5); rgba[i + 3] = 255;
  }
  return encodePng(w, h, rgba);
}

function make(root) {
  fs.rmSync(root, { recursive: true, force: true });
  const d = (p) => { const f = path.join(root, p); fs.mkdirSync(path.dirname(f), { recursive: true }); return f; };
  // STL e duplicati
  const cube = writeStl([{ name: 'cubo', positions: box(20, 20, 20) }]);
  fs.writeFileSync(d('Calibrazione/cubo_calibrazione.stl'), cube);
  fs.writeFileSync(d('Calibrazione/cubo_calibrazione (1).stl'), cube);       // copia esatta
  fs.writeFileSync(d('Archivio vecchio/cubo-v2.stl'), writeStl([{ name: 'cubo', positions: box(20, 20, 20, 50, 10, 0) }])); // stessa geometria, spostata
  fs.writeFileSync(d('Vasi/vaso_cilindro.stl'), writeStl([{ name: 'vaso', positions: cylinder(30, 80) }]));
  fs.writeFileSync(d('Vasi/foto_vaso.png'), png(320, 240, [80, 160, 255]));
  fs.writeFileSync(d('Vasi/LEGGIMI.txt'), 'Stampare in modalità vaso, 0.2mm, PLA.\n');
  // OBJ
  const cubeObj = 'o Supporto\n' + [[0,0,0],[30,0,0],[30,0,10],[0,0,10],[0,15,0],[30,15,0],[30,15,10],[0,15,10]].map(v => `v ${v.join(' ')}`).join('\n') +
    '\nf 1 2 3 4\nf 5 8 7 6\nf 1 5 6 2\nf 2 6 7 3\nf 3 7 8 4\nf 5 1 4 8\n';
  fs.writeFileSync(d('Varie/supporto_cuffie.obj'), cubeObj);
  // 3MF Bambu con 2 piatti e 2 colori
  const m = modelFromObjects([
    { name: 'Base', positions: box(60, 40, 5), color: '#2E86FF', extruder: 1 },
    { name: 'Scritta', positions: box(40, 10, 3, 10, 15, 5), color: '#FF5A1F', extruder: 2 },
    { name: 'Gancio', positions: cylinder(8, 30), color: '#2E86FF', extruder: 1 },
  ], 'Portachiavi');
  m.objects[2].plate = 2;
  m.plates = [{ index: 1, name: 'Corpo', objectIds: [1, 2] }, { index: 2, name: 'Gancio', objectIds: [3] }];
  m.flavor = 'bambu';
  fs.writeFileSync(d('Progetti/portachiavi_bambu.3mf'), write3mf(m, 'bambu'));
  // G-code con miniatura e stime
  const thumb = png(96, 96, [255, 120, 60]).toString('base64');
  const lines = thumb.match(/.{1,78}/g).map(l => `; ${l}`).join('\n');
  let g = `; generated by PrusaSlicer 2.8.1+linux\n;\n; thumbnail begin 96x96 ${thumb.length}\n${lines}\n; thumbnail end\n;\nG21\nG90\nM82\nG92 E0\n`;
  for (let L = 0; L < 40; L++) {
    const z = 0.2 + L * 0.2; g += `;LAYER_CHANGE\n;Z:${z.toFixed(2)}\nG1 Z${z.toFixed(2)} F3000\n;TYPE:${L % 2 ? 'Perimeter' : 'External perimeter'}\n`;
    let e = 0; for (let i = 0; i <= 36; i++) { const a = i / 36 * Math.PI * 2; e += 0.05; g += `G1 X${(100 + Math.cos(a) * 20).toFixed(3)} Y${(100 + Math.sin(a) * 20).toFixed(3)} E${e.toFixed(4)}\n`; }
    g += 'G92 E0\n';
  }
  g += '; filament used [mm] = 1234.56\n; filament used [g] = 3.72\n; estimated printing time (normal mode) = 1h 2m 3s\n; filament_type = PETG\n; layer_height = 0.2\n';
  fs.writeFileSync(d('Progetti/anello.gcode'), g);
  // Laser: LightBurn con miniatura e DXF
  fs.writeFileSync(d('Laser/sottobicchiere.lbrn2'), `<?xml version="1.0" encoding="UTF-8"?>\n<LightBurnProject AppVersion="1.7.03" FormatVersion="1">\n<Thumbnail Source="${png(128, 128, [255, 90, 160]).toString('base64')}"/>\n<CutSetting type="Cut"><index Value="0"/></CutSetting>\n</LightBurnProject>\n`);
  let dxf = '0\nSECTION\n2\nENTITIES\n';
  for (let i = 0; i < 4; i++) dxf += `0\nCIRCLE\n8\n0\n62\n${i + 1}\n10\n${50 + i * 5}\n20\n50\n30\n0\n40\n${10 + i * 8}\n`;
  dxf += '0\nLINE\n8\n0\n10\n0\n20\n0\n30\n0\n11\n100\n21\n100\n31\n0\n0\nENDSEC\n0\nEOF\n';
  fs.writeFileSync(d('Laser/mandala.dxf'), dxf);
  // Archivio ZIP con modelli dentro
  fs.writeFileSync(d('Pacchetti/pack_miniature.zip'), Buffer.from(zipSync({
    'miniature/torre.stl': new Uint8Array(writeStl([{ name: 't', positions: cylinder(10, 50, 24) }])),
    'miniature/muro.stl': new Uint8Array(writeStl([{ name: 'm', positions: box(80, 8, 30) }])),
    'miniature/anteprima.png': new Uint8Array(png(200, 200, [90, 220, 140])),
    'LICENZA.txt': strToU8('CC BY 4.0'),
  })));
  // STEP (generato da script Python) e archivio 7z
  require('node:child_process').spawnSync('python3', [path.join(__dirname, 'make-step.py'), d('Progetti/staffa.step')]);
  const za = require('7zip-bin').path7za;
  try { fs.chmodSync(za, 0o755); } catch {}
  require('node:child_process').spawnSync(za, ['a', '-bd', '-bso0', d('Pacchetti/ricambi.7z'), path.join(root, 'Vasi/foto_vaso.png'), path.join(root, 'Varie/supporto_cuffie.obj')]);
  return root;
}

module.exports = { make, box, cylinder, png };
if (require.main === module) console.log(make(process.argv[2] || '/tmp/reticolo-lib'));
